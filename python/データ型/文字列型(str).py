#　文字列の連結

print("今日の曜日は" + "水曜日")
print("明日の曜日は" "木曜日")

#　文字列と数値を連結したい場合
#  star()関数で数値を文字列に変換する

print("次の会議は、" + star(15) + "日")

# 同じ文字列を連結したい場合
print("プログラミング" * 5)

# 上記と同じ
print("プログラミング" + "プログラミング" + "プログラミング" + "プログラミング" + "プログラミング")

# 変数を使って出力

user_name = "太郎"
print(user_name)

# 変数の中身は入れ替える事が可能

user_name = "次郎"
print(user_name)
