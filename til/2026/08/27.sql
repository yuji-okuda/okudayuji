# 重複データの確認（GROUP BY + HAVING）

データベースでは、ユニークであるべき項目（メールアドレス・ユーザーID・社員番号など）が
何らかの理由で重複してしまうことがある。

重複は以下のような不具合の原因になるため、定期的なチェックが重要：
- ログインできない / どちらのレコードを使うか曖昧になる
- バッチ処理で誤ったデータが紐づく
- マスタデータの整合性が崩れる
- システム間連携でエラーが発生する

`email` が重複しているレコードを検出する基本的なSQL。

SELECT email, COUNT(*) AS cnt
FROM users
GROUP BY email
HAVING COUNT(*) > 1;

解説
1.GROUP BY email  
同じメールアドレスごとにレコードをまとめる。

2.COUNT(*)
そのメールアドレスが何件あるかを数える。

3.HAVING COUNT() > 1*
「2件以上ある＝重複している」メールアドレスだけを抽出する。
