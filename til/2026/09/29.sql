# CASE WHEN

テーブルA
年度　｜　受付日
2009　｜　20090515
2010　｜　null
2011　｜　null
2018　｜　null
2022　｜　20220920
2025　｜　null

※上記テーブルの『受付日』の　null　に以下の値を入れる場合、
・年度が2015以下なら、受付日に　年度＋0831 を入れる
・年度が2016以上なら、受付日に　年度＋1031 を入れる

UPDATE テーブルA
SET 受付日 =
    CASE
        WHEN 年度 <= '2015' THEN 年度 || '0831'
        WHEN 年度 >= '2016' THEN 年度 || '1031'
    END
WHERE 受付日 IS NULL;
