#　突合SQLのテスト項目例

No.	テスト内容	テスト条件	期待結果
1	両テーブルに一致するデータが存在する場合	突合キーが一致するデータを登録	一致したデータが抽出される
2	突合元にのみデータが存在する場合	突合先に一致するキーがない	SQLのJOIN条件に応じた結果になる
3	突合先にのみデータが存在する場合	突合元に一致するキーがない	SQLのJOIN条件に応じた結果になる
4	突合キーがNULLの場合	片方または両方の突合キーをNULLにする	NULL同士を一致として扱わないことを確認
5	突合キーが重複する場合	突合先に同じキーを複数登録	JOINによるレコード増加が想定どおりであること
6	抽出条件に一致する場合	WHERE条件を満たすデータを登録	対象データのみ抽出される
7	抽出条件に一致しない場合	WHERE条件を満たさないデータを登録	対象データが抽出されない
8	複数条件がある場合	AND条件をすべて満たすデータを登録	条件をすべて満たすデータのみ抽出される
9	境界値の場合	日付・数値などの最小値／最大値を登録	想定した境界値のデータが正しく抽出される
10	該当データが0件の場合	抽出条件に該当するデータを登録しない	0件で正常終了する
11	全件取得の確認	対象となるデータを複数登録	想定した全件が抽出される
12	抽出結果の項目確認	JOINしたデータを抽出	各カラムに正しい値が設定される
